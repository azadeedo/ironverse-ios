"""Real exercise photos for exercises that have no generated demonstration yet.

Source: free-exercise-db (github.com/yuhonas/free-exercise-db), Unlicense /
public domain. tools/photo_map.json maps Ironverse ids to that dataset by hand
(only exact movement + equipment matches). For each one this downloads the start
and finish photos and writes ONE side-by-side "start -> finish" WebP:
  public/media/exercises/photo-<id>.webp       (960 px wide)
  public/media/exercises/photo-<id>-480.webp   (480 px wide)
and regenerates src/data/mediaPhotos.ts.

Usage: python tools/build_photos.py
"""
import io
import json
import os
import sys
import urllib.request

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main'
OUT = os.path.join(ROOT, 'public', 'media', 'exercises')
CACHE = os.path.join(os.environ.get('TEMP', '/tmp'), 'fedb', 'img')


def fetch(url, cache_name):
    path = os.path.join(CACHE, cache_name)
    if not os.path.exists(path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with urllib.request.urlopen(url, timeout=60) as r:
            open(path, 'wb').write(r.read())
    return Image.open(path).convert('RGB')


def label(img, text):
    d = ImageDraw.Draw(img)
    try:
        font = ImageFont.truetype('arialbd.ttf', 26)
    except OSError:
        font = ImageFont.load_default()
    w = d.textlength(text, font=font)
    d.rounded_rectangle([12, 12, 12 + w + 24, 52], radius=10, fill=(12, 17, 28))
    d.text((24, 16), text, fill=(245, 158, 11), font=font)


def main():
    mapping = {k: v for k, v in json.load(open(os.path.join(ROOT, 'tools', 'photo_map.json'), encoding='utf-8')).items() if not k.startswith('_')}
    data = json.loads(urllib.request.urlopen(f'{RAW}/dist/exercises.json', timeout=60).read())
    by_name = {e['name']: e for e in data}
    os.makedirs(OUT, exist_ok=True)
    done = {}
    for iv_id, name in sorted(mapping.items()):
        e = by_name.get(name)
        if not e or len(e.get('images', [])) < 1:
            print('  skip (no images):', iv_id, name)
            continue
        frames = [fetch(f'{RAW}/exercises/{p}', p.replace('/', '__')) for p in e['images'][:2]]
        h = 480
        frames = [f.resize((round(f.width * h / f.height), h), Image.LANCZOS) for f in frames]
        raw0 = frames[0].copy()  # unlabelled, for the thumbnail
        for f, t in zip(frames, ['1', '2']):
            label(f, t)
        gap = 8
        canvas = Image.new('RGB', (sum(f.width for f in frames) + gap * (len(frames) - 1), h), (12, 17, 28))
        x = 0
        for f in frames:
            canvas.paste(f, (x, 0))
            x += f.width + gap
        # square thumbnail from position 1 only, whole frame visible (no cropping)
        f0 = raw0
        f0.thumbnail((300, 300), Image.LANCZOS)
        thumb = Image.new('RGB', (320, 320), (12, 17, 28))
        thumb.paste(f0, ((320 - f0.width) // 2, (320 - f0.height) // 2))
        thumb.save(os.path.join(OUT, f'photo-{iv_id}-thumb.webp'), 'WEBP', quality=80, method=6)
        big = canvas.resize((960, round(canvas.height * 960 / canvas.width)), Image.LANCZOS)
        small = canvas.resize((480, round(canvas.height * 480 / canvas.width)), Image.LANCZOS)
        big.save(os.path.join(OUT, f'photo-{iv_id}.webp'), 'WEBP', quality=80, method=6)
        small.save(os.path.join(OUT, f'photo-{iv_id}-480.webp'), 'WEBP', quality=78, method=6)
        done[iv_id] = {'img': f'/media/exercises/photo-{iv_id}.webp', 'imgSmall': f'/media/exercises/photo-{iv_id}-480.webp',
                       'thumb': f'/media/exercises/photo-{iv_id}-thumb.webp', 'kind': 'photo',
                       'credit': 'Real photos of the two key positions (free-exercise-db, public domain) — check the form cues too.'}
        print('  ok', iv_id)
    ts = ['// GENERATED by tools/build_photos.py — real start/finish photos from free-exercise-db',
          '// (github.com/yuhonas/free-exercise-db, Unlicense / public domain), matched by hand in',
          '// tools/photo_map.json. Used only where there is no generated demonstration (see media.ts).',
          "import type { MediaEntry } from './media'",
          'export const PHOTO_MEDIA: Record<string, MediaEntry> = ' + json.dumps(done, indent=2, ensure_ascii=False)]
    open(os.path.join(ROOT, 'src', 'data', 'mediaPhotos.ts'), 'w', encoding='utf-8', newline='\n').write('\n'.join(ts) + '\n')
    print(f'{len(done)} photos written')


if __name__ == '__main__':
    sys.exit(main())
