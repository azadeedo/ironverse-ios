//
// loadMode note: selectorised machines and cables are 'stack'; plate-loaded
// machines, fixed dumbbells, the trap bar and kettlebells are 'plate'; carries,
// sled work and cardio are 'time'.
//
// equipment note: AnyEquipment has no key for every single selectorised unit on
// a gym floor. Where no exact key exists the closest real family key is used so
// the "Flex 24/7" profile picks the exercise up correctly:
//   lateral raise machine -> 'shoulder-press-machine'
//   reverse pec deck / machine fly -> 'pec-deck'
//   biceps curl machine / machine preacher -> 'preacher-bench'
//   seated dip machine -> 'assisted-pullup'
//   triceps extension machine -> 'cable-station'
