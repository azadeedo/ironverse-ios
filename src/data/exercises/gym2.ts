//   iso-lateral row -> 'chest-supported-row'
//   glute kickback machine -> 'hip-thrust-machine'
//   belt squat -> low cable + cable station (dip belt on the low pulley works)
//   standing leg curl -> 'lying-leg-curl'
//   45-degree back extension / reverse hyper -> 'bench'
