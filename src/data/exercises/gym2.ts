// crossover range, neutral and single-arm pulldowns, iso-lateral plate-loaded
// rows, the arm machines, the glute and hamstring units, landmine and trap-bar
// work, and the cardio floor.
//
// Pose conventions per _reference.ts: figure faces right; arm direction =
// torso + shoulder (0 down, 90 forward, 180 overhead); elbow + = flexion;
